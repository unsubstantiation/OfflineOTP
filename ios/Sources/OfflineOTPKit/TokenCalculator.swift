import Foundation
import CryptoKit

/// The hash an entry uses for the HMAC half of its token; the stored spelling is an enum name.
public enum OtpHashAlgorithm: String, CaseIterable, Equatable {
    case sha1 = "SHA1"
    case sha256 = "SHA256"
    case sha512 = "SHA512"
}

/// One-time password generation: RFC 4226 HOTP, RFC 6238 TOTP, Steam Guard and mOTP.
///
/// This is a port of `core/src/main/kotlin/org/shadowice/flocke/andotp/Utilities/TokenCalculator.kt`
/// and must produce the same digits for the same seed, time step and hash. The fixed vectors in
/// `Tests/OfflineOTPKitTests/Fixtures/token-vectors.json` are generated by an independent Python
/// implementation (`scripts/ios/generate-token-vectors.py`) that is itself checked against the
/// published RFC 4226 and RFC 6238 vectors.
public enum TokenCalculator {
    public static let totpDefaultPeriod = 30
    public static let totpDefaultDigits = 6
    public static let hotpInitialCounter: Int64 = 1
    public static let steamDefaultDigits = 5
    /// mOTP rolls over every 10 seconds, independent of the period stored on the entry.
    public static let motpStepSeconds: Int64 = 10

    /// Steam's token alphabet, in mapping order; no vowels and no `L`, so a code cannot be misread.
    public static let steamAlphabet = Array("23456789BCDFGHJKMNPQRTVWXY")

    /// The raw 31-bit truncated value both HOTP and TOTP are built from.
    static func truncate(secret: [UInt8], counter: Int64, algorithm: OtpHashAlgorithm) throws -> UInt32 {
        guard !secret.isEmpty else { throw TokenError.invalidSecret }
        let message = withUnsafeBytes(of: counter.bigEndian) { Data($0) }
        let key = SymmetricKey(data: Data(secret))
        let mac: [UInt8]
        switch algorithm {
        case .sha1:
            // CryptoKit keeps SHA-1 in `Insecure`: the format requires it for legacy entries.
            mac = Array(HMAC<Insecure.SHA1>.authenticationCode(for: message, using: key))
        case .sha256:
            mac = Array(HMAC<SHA256>.authenticationCode(for: message, using: key))
        case .sha512:
            mac = Array(HMAC<SHA512>.authenticationCode(for: message, using: key))
        }
        guard let last = mac.last else { throw TokenError.invalidSecret }
        let offset = Int(last & 0x0F)
        guard offset + 4 <= mac.count else { throw TokenError.invalidSecret }
        return (UInt32(mac[offset] & 0x7F) << 24)
            | (UInt32(mac[offset + 1] & 0xFF) << 16)
            | (UInt32(mac[offset + 2] & 0xFF) << 8)
            | UInt32(mac[offset + 3] & 0xFF)
    }

    /// RFC 4226 HOTP as a zero-padded string.
    public static func hotp(secret: [UInt8], counter: Int64, digits: Int,
                            algorithm: OtpHashAlgorithm) throws -> String {
        try InputPolicy.validateTokenParameters(period: totpDefaultPeriod, digits: digits, counter: counter)
        let value = try truncate(secret: secret, counter: counter, algorithm: algorithm)
        return padded(Int64(value) % powerOfTen(digits), digits: digits)
    }

    /// RFC 6238 TOTP as a zero-padded string; `offset` shifts the time step.
    public static func totp(secret: [UInt8], period: Int, unixTime: Int64, digits: Int,
                            algorithm: OtpHashAlgorithm, offset: Int = 0) throws -> String {
        try InputPolicy.validateTokenParameters(period: period, digits: digits, counter: 0)
        let value = try truncate(secret: secret, counter: unixTime / Int64(period) + Int64(offset),
                                 algorithm: algorithm)
        return padded(Int64(value) % powerOfTen(digits), digits: digits)
    }

    /// Steam Guard: the raw TOTP value mapped onto the 26-character alphabet, least significant
    /// character first, as Steam's client does.
    public static func steam(secret: [UInt8], period: Int, unixTime: Int64, digits: Int,
                             algorithm: OtpHashAlgorithm, offset: Int = 0) throws -> String {
        try InputPolicy.validateTokenParameters(period: period, digits: digits, counter: 0)
        guard digits == steamDefaultDigits else { throw InputPolicyError.invalidTokenParameters }
        var value = try truncate(secret: secret, counter: unixTime / Int64(period) + Int64(offset),
                                 algorithm: algorithm)
        var out = ""
        for _ in 0..<digits {
            out.append(steamAlphabet[Int(value % UInt32(steamAlphabet.count))])
            value /= UInt32(steamAlphabet.count)
        }
        return out
    }

    /// Legacy mOTP: the first six hex digits of `MD5(step + seed + PIN)`, in a fixed 10-second step.
    ///
    /// MD5 is required by the mOTP specification and is not used here as a password hash;
    /// the value is a short-lived OTP, not a stored credential. Changing the hash would
    /// break every existing mOTP token.
    // codeql[swift/weak-sensitive-data-hashing] — mOTP is defined as MD5 per spec; not a password hash.
    // lgtm[swift/weak-sensitive-data-hashing] — intentional: MOTP spec requires MD5.
    public static func motp(pin: String, secret: String, unixTime: Int64, offset: Int = 0) -> String {
        let step = (unixTime / motpStepSeconds) + Int64(offset)
        let digest = Insecure.MD5.hash(data: Data("\(step)\(secret)\(pin)".utf8))
        let hex = digest.map { String(format: "%02x", $0) }.joined()
        return String(hex.prefix(6))
    }

    private static func powerOfTen(_ digits: Int) -> Int64 {
        (0..<digits).reduce(1) { value, _ in value * 10 }
    }

    private static func padded(_ value: Int64, digits: Int) -> String {
        var text = String(value)
        while text.count < digits { text = "0" + text }
        return text
    }
}

public enum TokenError: Error, Equatable {
    case invalidSecret
}
