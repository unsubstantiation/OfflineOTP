#!/usr/bin/env python3
"""Writes the Swift thumbnail catalog from the Kotlin one.

`ThumbnailCatalog` in `:core` decides which persisted logo name an entry carries, and both JVM
clients apply it whenever an entry is created or imported. The iOS client has no logo artwork, but it
writes the same *name*, because the name is what the other clients read back: an account imported
here and then opened on Android must show the same logo it would have shown had the phone imported it.

Keeping a hand-copied list of ~400 names in two languages would drift within a week, so the Swift
file is generated from the Kotlin source and this script is run in *verify* mode by CI: a change to
the Kotlin catalog that is not followed by `--write` fails the build instead of shipping a stale list.

Usage:
    scripts/ios/generate-thumbnail-catalog.py --write   # after an intentional catalog change
    scripts/ios/generate-thumbnail-catalog.py           # verify (this is what CI runs)
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
KOTLIN = (ROOT / "core/src/main/kotlin/org/shadowice/flocke/andotp/Utilities/"
          "ThumbnailCatalog.kt")
SWIFT = ROOT / "ios/Sources/OfflineOTPKit/ThumbnailCatalog.swift"

HEADER = '''import Foundation

// Generated by `scripts/ios/generate-thumbnail-catalog.py` from
// `core/src/main/kotlin/org/shadowice/flocke/andotp/Utilities/ThumbnailCatalog.kt`.
// Do not edit it by hand: change the Kotlin catalog and run the generator with `--write`.
// `scripts/tests/test_ios_app.py` fails when the two disagree.

/// The persisted logo names and the issuer matching rules of `ThumbnailCatalog` in `:core`.
///
/// The iOS client draws no logos, but it still stores the *name* an entry's issuer resolves to,
/// because that name is what the Android app and the desktop client read back. An account added or
/// imported here therefore keeps the same logo on the other clients as if they had added it
/// themselves, instead of resetting to the generic mark.
public enum ThumbnailCatalog {
    /// The fallback for an issuer no name matches — `ThumbnailCatalog.DEFAULT_NAME`.
    public static let defaultName = "Default"

    /// Every persisted name, in the declaration order the picker and stored documents rely on.
    public static let names: [String] = [
'''

FOOTER = '''    ]

    /// Issuer spellings that are the same brand but share no spelling with the persisted name.
    private static let aliases: [String: String] = [
'''

RUNTIME = '''    ]

    /// A stored name, tolerating an unknown or missing one by falling back to `defaultName`.
    public static func normalizeName(_ name: String?) -> String { exactName(name) ?? defaultName }

    /// Exact name, then the alias table, then the first whole-word match in declaration order, then
    /// the default — the same order `resolveName` applies on the JVM.
    public static func resolveName(_ issuer: String) -> String {
        exactName(issuer) ?? aliasName(issuer) ?? fuzzyName(issuer) ?? defaultName
    }

    /// Lowercase letters and digits only, so punctuation and spacing cannot break a match.
    static func fold(_ value: String) -> String {
        String(value.lowercased().filter { $0.isLetter || $0.isNumber })
    }

    /// Case-insensitive exact match in declaration order, then a match ignoring punctuation.
    static func exactName(_ value: String?) -> String? {
        guard let value else { return nil }
        if let exact = names.first(where: { $0.caseInsensitiveCompare(value) == .orderedSame }) {
            return exact
        }
        let folded = fold(value)
        guard !folded.isEmpty else { return nil }
        return names.first { fold($0) == folded }
    }

    static func aliasName(_ value: String) -> String? { aliases[fold(value)] }

    /// The first name that appears as a whole word in `value`, ignoring case.
    static func fuzzyName(_ value: String) -> String? {
        for name in names {
            let pattern = "\\\\b" + NSRegularExpression.escapedPattern(for: name) + "\\\\b"
            let options: NSRegularExpression.Options = [.caseInsensitive]
            guard let expression = try? NSRegularExpression(pattern: pattern, options: options)
            else { continue }
            let range = NSRange(value.startIndex..., in: value)
            if expression.firstMatch(in: value, options: [], range: range) != nil { return name }
        }
        return nil
    }
}
'''


def kotlin_names(text: str) -> list[str]:
    block = re.search(r"val NAMES: List<String> = listOf\((.*?)\n    \)", text, re.S)
    if block is None:
        raise SystemExit("the NAMES list moved; the generator needs updating")
    return re.findall(r'"((?:[^"\\]|\\.)*)"', block.group(1))


def kotlin_aliases(text: str) -> list[tuple[str, str]]:
    block = re.search(r"private val ALIASES: Map<String, String> = mapOf\((.*?)\n    \)", text, re.S)
    if block is None:
        raise SystemExit("the ALIASES map moved; the generator needs updating")
    return re.findall(r'"((?:[^"\\]|\\.)*)" to "((?:[^"\\]|\\.)*)"', block.group(1))


def swift_source() -> str:
    text = KOTLIN.read_text(encoding="utf-8")
    names = kotlin_names(text)
    aliases = kotlin_aliases(text)
    if not names or names[0] != "Default":
        raise SystemExit("the catalog must start with Default")
    if len(set(names)) != len(names):
        raise SystemExit("duplicate name in the catalog")
    body = HEADER
    for name in names:
        body += f'        "{name}",\n'
    body += FOOTER
    for key, value in aliases:
        if value not in names:
            raise SystemExit(f"alias {key!r} points at a name that is not in the catalog: {value!r}")
        body += f'        "{key}": "{value}",\n'
    body += RUNTIME
    return body


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="rewrite the Swift file")
    arguments = parser.parse_args()

    expected = swift_source()
    if arguments.write:
        SWIFT.write_text(expected, encoding="utf-8")
        print(f"wrote {SWIFT.relative_to(ROOT)}")
        return 0
    actual = SWIFT.read_text(encoding="utf-8") if SWIFT.exists() else ""
    if actual != expected:
        print("ios/Sources/OfflineOTPKit/ThumbnailCatalog.swift is stale; run "
              "scripts/ios/generate-thumbnail-catalog.py --write", file=sys.stderr)
        return 1
    print("thumbnail catalog is current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
