#!/usr/bin/env python3
"""Generate native theme bindings from one catalogue, without any build-time downloads.
Platform resource names and color values are preserved. Generated files are checked in.
"""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def outputs():
    data = json.loads((ROOT / 'shared/theme/forest.json').read_text())
    tokens = data['tokens']
    assert all(re.fullmatch(r'[0-9A-F]{8}', value) for value in tokens.values())
    header = '// Generated by scripts/generate-theme.py; edit shared/theme/forest.json.\n'
    kotlin = header + 'package com.fairuniversal.offlineotp.ui.theme\n\nimport androidx.compose.ui.graphics.Color\n\nobject ForestPalette {\n'
    for name, argb in tokens.items():
        kotlin += f'    val {name} = Color(0x{argb})\n'
    kotlin += '''
    /** Stable UTF-16 hash, unchanged from the original JVM tile renderer. */
    fun letterTileTint(seed: String): Color {
        val palette = listOf(
'''
    kotlin += '            ' + ', '.join(f'Color(0x{color})' for color in data['letterTileColors']) + '\n'
    kotlin += '''        )
        if (seed.isEmpty()) return palette.first()
        var hash = 0
        for (character in seed) hash = hash * 31 + character.code
        return palette[((hash % palette.size) + palette.size) % palette.size]
    }
}
'''
    # UIKit adapters receive native colors from Kotlin, generated from the same tokens.
    native = header + '@file:OptIn(kotlinx.cinterop.ExperimentalForeignApi::class)\n\n'
    native += 'package com.fairuniversal.offlineotp.ui.platform\n\nimport platform.UIKit.UIColor\n\nobject IosHostPalette {\n'
    for name, argb in tokens.items():
        a, r, g, b = (argb[i:i+2] for i in (0, 2, 4, 6))
        alpha = '1.0' if a == 'FF' else f'{int(a, 16) / 255:.8f}'.rstrip('0').rstrip('.')
        native += (f'    val {name} = UIColor(red = 0x{r} / 255.0, '
                   f'green = 0x{g} / 255.0, blue = 0x{b} / 255.0, alpha = {alpha})\n')
    native += '}\n'
    xml = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/generate-theme.py; edit shared/theme/forest.json. -->\n<resources>\n'
    for name, token in data['androidResources'].items():
        value = token if token.startswith('@') else '#' + (tokens[token][2:] if tokens[token].startswith('FF') else tokens[token])
        xml += f'    <color name="{name}">{value}</color>\n'
    xml += '</resources>\n'
    return {'ui-foundation/src/commonMain/kotlin/com/fairuniversal/offlineotp/ui/theme/ForestPalette.kt': kotlin,
            'ui-foundation/src/iosMain/kotlin/com/fairuniversal/offlineotp/ui/platform/IosHostPalette.kt': native,
            'app/src/main/res/values/colors.xml': xml}


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for name, text in outputs().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != text: stale.append(name)
        else: path.write_text(text)
    if stale: raise SystemExit('Run scripts/generate-theme.py; stale output: ' + ', '.join(stale))
