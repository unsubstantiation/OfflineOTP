#!/usr/bin/env python3
"""Generate the shared brand-artwork index from the Android thumbnail enum.

The Android app binds each persisted thumbnail name to a vector drawable through the
`EntryThumbnails` enum in `app/.../Utilities/EntryThumbnail.kt`. Both JVM (`:core`) and
Kotlin/Native (`:ui-contract` / `:ui-foundation`) clients need the same name -> drawable-file
mapping without referencing Android resources, so this script emits:
  - `core/src/main/kotlin/com/fairuniversal/offlineotp/Utilities/ThumbnailAssets.kt`
  - `ui-contract/src/commonMain/kotlin/com/fairuniversal/offlineotp/ui/portable/PortableThumbnailAssets.kt`

Usage:
    python3 scripts/branding/generate_thumbnail_assets.py          # rewrite generated files
    python3 scripts/branding/generate_thumbnail_assets.py --check  # exit 1 if either file is stale

`scripts/tests/test_desktop_issuer_icons.py` runs the --check form, so the generated tables can
never silently drift away from the enum.
"""
import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
ENUM_SOURCE = ROOT / "app/src/main/kotlin/com/fairuniversal/offlineotp/Utilities/EntryThumbnail.kt"
DRAWABLE_DIR = ROOT / "app/src/main/res/drawable"
OUTPUT = ROOT / "core/src/main/kotlin/com/fairuniversal/offlineotp/Utilities/ThumbnailAssets.kt"
PORTABLE_OUTPUT = (
    ROOT
    / "ui-contract/src/commonMain/kotlin/com/fairuniversal/offlineotp/ui/portable/PortableThumbnailAssets.kt"
)

# `Name(R.drawable.thumb_x)` / `Name(R.drawable.thumb_x, AssetType.Bitmap)`.
ENTRY = re.compile(r"^\s{8}(\w+)\(R\.(?:drawable|mipmap)\.(\w+)", re.MULTILINE)


def entries():
    """(thumbnail name, drawable file) pairs in enum order, skipping the letter-tile default."""
    source = ENUM_SOURCE.read_text(encoding="utf-8")
    body = source.split("enum class EntryThumbnails", 1)[1]
    found = []
    for name, resource in ENTRY.findall(body):
        if name == "Default":
            continue
        found.append((name, resource))
    if not found:
        raise SystemExit("no EntryThumbnails entries found; the enum formatting changed")
    return found


def render_core(pairs):
    lines = [
        "package com.fairuniversal.offlineotp.Utilities",
        "",
        "/**",
        " * Bundled brand artwork shared by both clients: which Android vector drawable backs each",
        " * persisted thumbnail name. `:core` stays Android-free, so this holds file *names* only; the",
        " * Android UI binds them to `R.drawable` in [EntryThumbnail], and the desktop client loads the",
        " * same vector XML files, which its build copies from `app/src/main/res/drawable`.",
        " *",
        " * Generated by `scripts/branding/generate_thumbnail_assets.py` from the `EntryThumbnails`",
        " * enum; do not edit by hand. `scripts/tests/test_desktop_issuer_icons.py` fails when this",
        " * table and the enum disagree.",
        " */",
        "object ThumbnailAssets {",
        "    /** Drawable file base name (without `.xml`) for a thumbnail name. */",
        "    private val DRAWABLES: Map<String, String> = mapOf(",
    ]
    for index, (name, resource) in enumerate(pairs):
        separator = "," if index + 1 < len(pairs) else ""
        lines.append(f'        "{name}" to "{resource}"{separator}')
    lines += [
        "    )",
        "",
        "    /** Bundled vector file for [name], or null when the name has no bundled artwork. */",
        "    @JvmStatic",
        "    fun drawableFile(name: String?): String? = if (name == null) null else DRAWABLES[name]",
        "",
        "    /** Every bundled drawable file, without duplicates: some names share a mark. */",
        "    @JvmStatic",
        "    fun files(): Set<String> = DRAWABLES.values.toSet()",
        "",
        "    /** Number of bundled brand marks; the default letter tile is not counted. */",
        "    @JvmStatic",
        "    fun count(): Int = files().size",
        "}",
        "",
    ]
    return "\n".join(lines)


def render_portable(pairs):
    lines = [
        "package com.fairuniversal.offlineotp.ui.portable",
        "",
        "/**",
        " * Toolkit-free multiplatform brand-artwork index shared across Android, Desktop and iOS.",
        " * Maps each persisted thumbnail name onto its bundled `thumb_*.xml` vector drawable stem.",
        " *",
        " * Generated by `scripts/branding/generate_thumbnail_assets.py` from `EntryThumbnails`;",
        " * do not edit by hand.",
        " */",
        "object PortableThumbnailAssets {",
        "    private val DRAWABLES: Map<String, String> = mapOf(",
    ]
    for index, (name, resource) in enumerate(pairs):
        separator = "," if index + 1 < len(pairs) else ""
        lines.append(f'        "{name}" to "{resource}"{separator}')
    lines += [
        "    )",
        "",
        "    /** Bundled vector file base name (without `.xml`) for [name], or null when unmapped. */",
        "    fun drawableFile(name: String?): String? = if (name == null) null else DRAWABLES[name]",
        "",
        "    /** Every bundled drawable stem without duplicates. */",
        "    fun files(): Set<String> = DRAWABLES.values.toSet()",
        "",
        "    /** Number of distinct bundled brand vector drawables. */",
        "    fun count(): Int = files().size",
        "}",
        "",
    ]
    return "\n".join(lines)


def render():
    return render_core(entries())


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail instead of rewriting when stale")
    args = parser.parse_args(argv)

    pairs = entries()
    missing = [resource for _, resource in pairs
               if not (DRAWABLE_DIR / f"{resource}.xml").exists()]
    if missing:
        print("missing drawables: " + ", ".join(sorted(missing)), file=sys.stderr)
        return 1

    targets = [
        (OUTPUT, render_core(pairs)),
        (PORTABLE_OUTPUT, render_portable(pairs)),
    ]
    stale = [
        (target, expected)
        for target, expected in targets
        if (target.read_text(encoding="utf-8") if target.exists() else None) != expected
    ]
    if not stale:
        return 0
    if args.check:
        for target, _ in stale:
            print(f"{target.relative_to(ROOT)} is stale; run {pathlib.Path(__file__).name}", file=sys.stderr)
        return 1
    for target, expected in stale:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(expected, encoding="utf-8")
        print(f"wrote {target.relative_to(ROOT)} with {len(pairs)} brand marks")
    return 0


if __name__ == "__main__":
    sys.exit(main())
