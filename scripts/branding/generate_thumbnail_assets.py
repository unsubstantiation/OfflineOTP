#!/usr/bin/env python3
"""Generate the shared brand-artwork index from the Android thumbnail enum.

The Android app binds each persisted thumbnail name to a vector drawable through the
`EntryThumbnails` enum in `app/.../Utilities/EntryThumbnail.kt`. The desktop client needs the
same name -> drawable-file mapping but cannot reference Android resources, so this script emits
an Android-free table into `:core` and the desktop build copies the referenced `thumb_*.xml`
files onto its classpath (see desktop/build.gradle).

Usage:
    python3 scripts/branding/generate_thumbnail_assets.py          # rewrite the generated file
    python3 scripts/branding/generate_thumbnail_assets.py --check  # exit 1 if it is stale

`scripts/tests/test_desktop_issuer_icons.py` runs the --check form, so the generated table can
never silently drift away from the enum.
"""
import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
ENUM_SOURCE = ROOT / "app/src/main/kotlin/org/shadowice/flocke/andotp/Utilities/EntryThumbnail.kt"
DRAWABLE_DIR = ROOT / "app/src/main/res/drawable"
OUTPUT = ROOT / "core/src/main/kotlin/org/shadowice/flocke/andotp/Utilities/ThumbnailAssets.kt"

# `Name(R.drawable.thumb_x)` / `Name(R.drawable.thumb_x, AssetType.Bitmap)`.
ENTRY = re.compile(r"^\s{8}(\w+)\(R\.(?:drawable|mipmap)\.(\w+)", re.MULTILINE)


def entries():
    """(thumbnail name, drawable file) pairs in enum order, skipping the letter-tile default."""
    source = ENUM_SOURCE.read_text(encoding="utf-8")
    body = source.split("enum class EntryThumbnails", 1)[1]
    found = []
    for name, resource in ENTRY.findall(body):
        if name == "Default":
            continue
        found.append((name, resource))
    if not found:
        raise SystemExit("no EntryThumbnails entries found; the enum formatting changed")
    return found


def render():
    lines = [
        "package org.shadowice.flocke.andotp.Utilities",
        "",
        "/**",
        " * Bundled brand artwork shared by both clients: which Android vector drawable backs each",
        " * persisted thumbnail name. `:core` stays Android-free, so this holds file *names* only; the",
        " * Android UI binds them to `R.drawable` in [EntryThumbnail], and the desktop client loads the",
        " * same vector XML files, which its build copies from `app/src/main/res/drawable`.",
        " *",
        " * Generated by `scripts/branding/generate_thumbnail_assets.py` from the `EntryThumbnails`",
        " * enum; do not edit by hand. `scripts/tests/test_desktop_issuer_icons.py` fails when this",
        " * table and the enum disagree.",
        " */",
        "object ThumbnailAssets {",
        "    /** Drawable file base name (without `.xml`) for a thumbnail name. */",
        "    private val DRAWABLES: Map<String, String> = mapOf(",
    ]
    pairs = entries()
    for index, (name, resource) in enumerate(pairs):
        separator = "," if index + 1 < len(pairs) else ""
        lines.append(f'        "{name}" to "{resource}"{separator}')
    lines += [
        "    )",
        "",
        "    /** Bundled vector file for [name], or null when the name has no bundled artwork. */",
        "    @JvmStatic",
        "    fun drawableFile(name: String?): String? = if (name == null) null else DRAWABLES[name]",
        "",
        "    /** Every bundled drawable file, without duplicates: some names share a mark. */",
        "    @JvmStatic",
        "    fun files(): Set<String> = DRAWABLES.values.toSet()",
        "",
        "    /** Number of bundled brand marks; the default letter tile is not counted. */",
        "    @JvmStatic",
        "    fun count(): Int = files().size",
        "}",
        "",
    ]
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail instead of rewriting when stale")
    args = parser.parse_args(argv)

    expected = render()
    current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else None
    missing = [resource for _, resource in entries()
               if not (DRAWABLE_DIR / f"{resource}.xml").exists()]
    if missing:
        print("missing drawables: " + ", ".join(sorted(missing)), file=sys.stderr)
        return 1
    if current == expected:
        return 0
    if args.check:
        print(f"{OUTPUT.relative_to(ROOT)} is stale; run {pathlib.Path(__file__).name}", file=sys.stderr)
        return 1
    OUTPUT.write_text(expected, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)} with {len(entries())} brand marks")
    return 0


if __name__ == "__main__":
    sys.exit(main())
