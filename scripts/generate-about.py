#!/usr/bin/env python3
"""One About content source for shared Compose and Android default resources.
Run with --check in tests; generated files are committed so normal builds need no generator.
Existing Android translations and native library/flavor integrations remain intact.
"""
import argparse
import json
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]

def outputs():
    data = json.loads((ROOT / 'shared/about/content.json').read_text())
    quote = lambda s: json.dumps(s, ensure_ascii=False)
    strings = data['strings']
    links = data['links']
    kotlin = '// Generated by scripts/generate-about.py; edit shared/about/content.json.\npackage com.fairuniversal.offlineotp.ui.vault\n\n'
    kotlin += 'data class AboutLink(val id: String, val label: String, val url: String)\n\nobject AboutInfo {\n'
    kotlin += '    const val description = '+quote(strings['about_description'])+'\n'
    kotlin += '    const val copyright = '+quote(strings['about_copyright'])+'\n'
    kotlin += '    const val attribution = '+quote(data['attribution'])+'\n'
    kotlin += '    val links = listOf(\n'+',\n'.join('        AboutLink('+', '.join(quote(x[k]) for k in ('id','label','url'))+')' for x in links)+'\n    )\n'
    kotlin += '    fun url(id: String): String = links.first { it.id == id }.url\n'
    disclaimers=[strings[f'about_thumbnails_disclaimer_no{i}'] for i in range(1,5)]
    kotlin += '    val thumbnailDisclaimer = listOf('+', '.join(map(quote,disclaimers))+')\n}\n'
    xml = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/generate-about.py; edit shared/about/content.json. -->\n<resources>\n'
    for key,value in strings.items():
        attr=' translatable="false"' if key in ('about_copyright','about_name_author1','about_name_author2','about_name_author_original') else ''
        xml += f'    <string name="{key}"{attr}>{escape(value).replace(chr(39), chr(92)+chr(39))}</string>\n'
    xml += '</resources>\n'
    swift = '// Generated by scripts/generate-about.py; edit shared/about/content.json.\n'
    swift += '/// Fixed About links, supplied as identifiers to the native browser adapter.\n'
    swift += 'enum AboutInfo {\n'
    swift += '    static func url(id: String) -> String {\n'
    swift += '        let links = [\n'
    swift += ',\n'.join('            ' + quote(x['id']) + ': ' + quote(x['url']) for x in links)
    swift += '\n        ]\n'
    swift += '        return links[id] ?? ""\n'
    swift += '    }\n'
    swift += '}\n'
    return {'ui-foundation/src/commonMain/kotlin/com/fairuniversal/offlineotp/ui/vault/AboutInfo.kt':kotlin,
            'app/src/main/res/values/strings_about.xml':xml,
            'ios/App/Sources/AboutInfo.swift':swift}

if __name__ == '__main__':
    parser=argparse.ArgumentParser(); parser.add_argument('--check',action='store_true'); args=parser.parse_args()
    stale=[]
    for name,text in outputs().items():
        path=ROOT/name
        if args.check:
            if not path.exists() or path.read_text()!=text: stale.append(name)
        else: path.write_text(text)
    if stale: raise SystemExit('Stale About content; run scripts/generate-about.py: '+', '.join(stale))
